/* Run with: node tests/browser-smoke.cjs [absolute Playwright module directory] [URL]. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const { chromium } = require(process.argv[2] || 'playwright');
const root = path.resolve(__dirname, '..');
const output = path.resolve(root, '..', 'hw3-verification');
fs.mkdirSync(output, { recursive: true });
const server = http.createServer((req, res) => {
  const pathname = decodeURIComponent(new URL(req.url, 'http://localhost').pathname);
  const filename = path.resolve(root, '.' + (pathname === '/' ? '/homework-3.html' : pathname));
  if (!filename.startsWith(root + path.sep)) { res.writeHead(403); res.end(); return; }
  const type = { '.js': 'text/javascript', '.html': 'text/html', '.css': 'text/css' }[path.extname(filename)] || 'application/octet-stream';
  fs.readFile(filename, (error, bytes) => { res.writeHead(error ? 404 : 200, { 'Content-Type': type }); res.end(error ? 'Not found' : bytes); });
});
(async () => {
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const browser = await chromium.launch({ channel: 'chrome', headless: true, downloadsPath: path.join(output, 'downloads') });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const response = await page.goto(process.argv[3] || `http://127.0.0.1:${server.address().port}/homework-3.html`);
    assert.equal(response.status(), 200);
    await page.waitForFunction(() => document.querySelectorAll('#study-rows tr').length === 9);
    assert.equal(await page.locator('#rank-rows tr').count(), 26);
    assert.equal(await page.locator('#frequency-chart .frequency-row').count(), 26);
    await page.locator('#message').fill('HELLO — Azərbaycan əıöşüç 🔐');
    assert.match(await page.locator('#caesar-cipher-out').innerText(), /^OLSSV/);
    await page.locator('#ecc-encrypt').click();
    await page.waitForFunction(() => document.querySelector('#ecc-status').textContent.includes('Restored'));
    assert.equal(await page.locator('#ecc-plain-out').innerText(), 'HELLO — Azərbaycan əıöşüç 🔐');
    await page.locator('#ecc-compare').click();
    await page.waitForFunction(() => document.querySelector('#attack-out').textContent.includes('Recovered d = 37'));
    assert.equal(await page.locator('#attack-comparison tr').count(), 2);
    await page.locator('#attack-target').selectOption('r');
    await page.locator('#attack-method').selectOption('bsgs');
    await page.locator('#ecc-attack').click();
    await page.waitForFunction(() => document.querySelector('#attack-out').textContent.includes('Recovered r = 11'));
    await page.locator('#tamper-run').click();
    await page.waitForFunction(() => document.querySelector('#tamper-status').textContent.includes('Rejected:'));
    await page.locator('#attack-bound').fill('5');
    await page.locator('#ecc-attack').click();
    await page.waitForFunction(() => document.querySelector('#attack-out').textContent.includes('No match'));
    await page.locator('#private-d').fill('0');
    await page.locator('#ecc-encrypt').click();
    await page.waitForFunction(() => document.querySelector('#ecc-status').classList.contains('error'));
    assert.equal(await page.locator('#public-key-out').innerText(), '—');
    await page.locator('#private-d').fill('37');
    await page.locator('#attack-bound').fill('64');
    await page.locator('#attack-ciphertext').fill('<img src=x onerror=alert(1)> KHOOR');
    await page.locator('#frequency-run').click();
    assert.equal(await page.locator('#rank-rows img').count(), 0);
    await page.locator('#rank-method').selectOption('ngram');
    assert.equal(await page.locator('#rank-rows tr').count(), 26);
    await page.locator('#rank-method').selectOption('exhaustive');
    assert.equal(await page.locator('#rank-rows tr').first().locator('td').first().innerText(), '0');
    await page.locator('#training-corpus').fill('');
    await page.locator('#frequency-run').click();
    assert.match(await page.locator('#frequency-result').innerText(), /needs A–Z/);
    await page.locator('#study-run').click();
    await page.waitForFunction(() => document.querySelector('#study-summary').classList.contains('error'));
    assert.equal(await page.locator('#export-study').isDisabled(), true);
    await page.reload();
    await page.waitForFunction(() => document.querySelectorAll('#study-rows tr').length === 9);
    await page.locator('#export-study').click();
    const csv = await page.locator('#csv-text').inputValue();
    assert.equal(csv.split('\n').length, 10);
    const downloadPromise = page.waitForEvent('download');
    await page.locator('#csv-download').click();
    const download = await downloadPromise;
    await download.saveAs(path.join(output, 'length-study.csv'));
    assert.equal(fs.readFileSync(path.join(output, 'length-study.csv'), 'utf8').split('\n').length, 10);
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: path.join(output, 'desktop.png'), fullPage: false });
    await page.locator('#ecc-encrypt').click();
    await page.waitForFunction(() => document.querySelector('#ecc-status').textContent.includes('Restored'));
    await page.locator('#ecc-demo').scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(output, 'ecc-desktop.png'), fullPage: false });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.evaluate(() => window.scrollTo(0, 0));
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1);
    assert.equal(overflow, false, 'Page must fit a 390px viewport');
    await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: false });
    await page.locator('#frequency-attack').scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(output, 'mobile-statistics.png'), fullPage: false });
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ status: 'PASS', url: page.url(), browser: await browser.version(), checks: ['ECC roundtrip', 'both searches', 'ephemeral attack', 'tamper rejection', 'invalid inputs', 'all 26 candidates', 'HTML escaping', 'study errors', 'CSV export', 'mobile layout', 'no uncaught errors'], screenshots: output }, null, 2));
  } finally { await browser.close(); server.close(); }
})().catch(e => { console.error(e); server.close(); process.exitCode = 1; });
